// Build only the immutable reviewed product commit; no registry publication.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {copyFileSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join, resolve} from 'node:path';
import {candidatePackEntry} from './candidate-helpers.mjs';

const binding = JSON.parse(readFileSync('candidate-binding.json'));
assert.equal(binding.name, 'semantic-release-workspace');
assert.match(binding.sha, /^[a-f0-9]{40}$/);
assert.match(binding.repository, /^https:\/\/github\.com\/enkhjile\/semantic-release-workspace(?:\.git)?$/);
assert.equal(process.version, binding.node);
assert.equal(execFileSync('npm', ['--version'], {encoding: 'utf8'}).trim(), binding.npm);
assert.ok(process.env.RUNNER_TEMP, 'Build scratch must be owned by this job');
const source = join(process.env.RUNNER_TEMP, 'shared-version-candidate-source');
mkdirSync(source, {recursive: false});
const git = (...args) => execFileSync('git', ['-C', source, ...args], {encoding: 'utf8'}).trim();
git('init');
git('remote', 'add', 'origin', binding.repository);
git('fetch', '--depth=1', '--no-tags', 'origin', binding.sha);
git('checkout', '--detach', 'FETCH_HEAD');
assert.equal(git('rev-parse', 'HEAD'), binding.sha);
const product = JSON.parse(readFileSync(join(source, 'package.json')));
assert.equal(product.name, binding.name);
assert.equal(product.packageManager, binding.productPackageManager);
assert.equal(product.devEngines?.runtime?.version, binding.productRuntime);
assert.match(product.packageManager, /^pnpm@\d+\.\d+\.\d+$/);
assert.equal(execFileSync('pnpm', ['--version'], {cwd: source, encoding: 'utf8'}).trim(), product.packageManager.slice(5));
const lockBefore = readFileSync(join(source, 'pnpm-lock.yaml'));
execFileSync('pnpm', ['install', '--frozen-lockfile', '--ignore-scripts', '--store-dir', join(process.env.RUNNER_TEMP, 'shared-version-pnpm-store')], {cwd: source, stdio: 'inherit'});
assert.equal(execFileSync('pnpm', ['exec', 'node', '--version'], {cwd: source, encoding: 'utf8'}).trim(), 'v' + binding.productRuntime);
execFileSync('pnpm', ['run', 'build'], {cwd: source, stdio: 'inherit'});
assert.deepEqual(readFileSync(join(source, 'pnpm-lock.yaml')), lockBefore, 'Candidate build changed the product lockfile');
assert.ok(process.env.ACCEPTANCE_NPM_CLI, 'Pinned npm CLI path is required');
assert.equal(execFileSync('pnpm', ['exec', 'node', process.env.ACCEPTANCE_NPM_CLI, '--version'], {cwd: source, encoding: 'utf8'}).trim(), binding.npm);
const packed = candidatePackEntry(execFileSync('pnpm', ['exec', 'node', process.env.ACCEPTANCE_NPM_CLI, 'pack', '--ignore-scripts', '--json'], {cwd: source, encoding: 'utf8'}), product);
const archive = join(source, packed.filename);
const bytes = readFileSync(archive);
assert.equal(createHash('sha256').update(bytes).digest('hex'), binding.tarballSha256);
assert.equal('sha512-' + createHash('sha512').update(bytes).digest('base64'), binding.tarballIntegrity);
assert.equal(packed.integrity, binding.tarballIntegrity);
const files = execFileSync('tar', ['-tzf', archive], {encoding: 'utf8'}).trim().split('\n').filter(p => !p.endsWith('/')).sort();
assert.deepEqual(files.map(p => p.replace(/^package\//, '')).sort(), Object.keys(binding.files).sort());
for (const path of files) assert.equal(createHash('sha256').update(execFileSync('tar', ['-xOf', archive, path])).digest('hex'), binding.files[path.replace(/^package\//, '')]);
mkdirSync('vendor', {recursive: true});
copyFileSync(archive, 'vendor/shared-version-candidate.tgz');
execFileSync('git', ['check-ignore', '--quiet', 'vendor/shared-version-candidate.tgz']);
const evidence = resolve('evidence/shared-version');
mkdirSync(evidence, {recursive: true});
writeFileSync(join(evidence, 'candidate-build.json'), JSON.stringify({status: 'PASS', sha: binding.sha, repository: binding.repository, node: process.version, npm: binding.npm, productPackageManager: product.packageManager, productRuntime: binding.productRuntime, productLockSha256: createHash('sha256').update(lockBefore).digest('hex'), tarballSha256: binding.tarballSha256, tarballIntegrity: binding.tarballIntegrity, files: binding.files}, null, 2) + '\n');
